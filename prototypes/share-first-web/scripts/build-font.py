"""Subset Inter (SIL Open Font License 1.1) into base64 WOFF and write src/font-data.ts.
Run: python3 scripts/build-font.py   (needs fontTools; Inter .otf files in FONT_DIR)
Embedding the font inside each exported SVG makes the PNG look identical on every device."""
import base64, io, os, sys
from fontTools import subset
from fontTools.ttLib import TTFont

FONT_DIR = os.environ.get("FONT_DIR", "/usr/share/fonts/opentype/inter")
WEIGHTS = {500: "Inter-Medium.otf", 600: "Inter-SemiBold.otf", 700: "Inter-Bold.otf", 800: "Inter-ExtraBold.otf"}
UNICODES = list(range(0x20, 0x7F)) + list(range(0xA0, 0x100)) + [0x131, 0x2010, 0x2011, 0x2012, 0x2013, 0x2014, 0x2015,
    0x2018, 0x2019, 0x201C, 0x201D, 0x2022, 0x2026, 0x2032, 0x2033, 0x2212]

def build(path):
    opts = subset.Options()
    opts.flavor = "woff"
    opts.layout_features = ["kern", "liga", "calt", "case", "tnum"]
    opts.drop_tables += ["DSIG"]
    f = TTFont(path)
    s = subset.Subsetter(opts)
    s.populate(unicodes=UNICODES)
    s.subset(f)
    f.flavor = "woff"
    buf = io.BytesIO()
    f.save(buf)
    return buf.getvalue()

out = ["// GENERATED by scripts/build-font.py. Do not edit.",
       "// Inter, Copyright 2016 The Inter Project Authors (https://github.com/rsms/inter), SIL Open Font License 1.1.",
       "// Subset to Latin + punctuation, WOFF, base64.", "export const FONT_FACES: Record<number, string> = {"]
total = 0
for w, name in WEIGHTS.items():
    data = build(os.path.join(FONT_DIR, name))
    total += len(data)
    out.append(f"  {w}: '{base64.b64encode(data).decode()}',")
out.append("};")
open(os.path.join(os.path.dirname(__file__), "..", "src", "font-data.ts"), "w").write("\n".join(out) + "\n")
print("wrote src/font-data.ts, woff bytes:", total)
